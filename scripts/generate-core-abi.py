"""Generate both language constants from the single ABI contract; --check never writes."""
import argparse
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def macro(name):
    return re.sub(r'([a-z0-9])([A-Z])', r'\1_\2',
                  re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', name)).upper()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    spec = json.loads((ROOT / 'corelib/abi/contract.json').read_text())
    limits, statuses = spec['limits'], spec['statuses']
    assert all(type(v) is int and 0 < v < 2**31 for v in limits.values())
    assert len(set(statuses.values())) == len(statuses)
    assert all(type(v) is int and -(2**31) < v < 2**31 for v in statuses.values())
    assert re.fullmatch('[0-9a-f]{40}', spec['upstream_commit'])
    version = spec['abi_version']
    assert type(version) is int and 0 < version < 2**32
    go = ('// Code generated by scripts/generate-core-abi.py; DO NOT EDIT.\n'
          'package bridge\n\nconst (\n'
          f'ABIVersion = {version}\nUpstreamCommit = "{spec["upstream_commit"]}"\n')
    go += ''.join(f'{k} = {v}\n' for k, v in limits.items()) + ')\n'
    go += 'const (\n' + ''.join(f'{k} Status = {v}\n' for k, v in statuses.items()) + ')\n'
    go = subprocess.check_output(['gofmt'], input=go, text=True)
    header = ('/* Generated by scripts/generate-core-abi.py; DO NOT EDIT. */\n'
              '#ifndef JUSTCONNECT_ABI_CONSTANTS_H\n#define JUSTCONNECT_ABI_CONSTANTS_H\n'
              '#include <stdint.h>\n'
              f'#define JC_ABI_VERSION UINT32_C({version})\n')
    header += ''.join(f'#define JC_{macro(k)} UINT32_C({v})\n' for k, v in limits.items())
    header += ''.join(f'#define JC_{macro(k)} ' +
                      (f'(-INT32_C({-v}))' if v < 0 else f'INT32_C({v})') + '\n'
                      for k, v in statuses.items()) + '#endif\n'
    for name, contents in [('corelib/internal/bridge/constants.go', go),
                           ('corelib/abi/constants.h', header)]:
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != contents:
                raise SystemExit(f'{name} differs from contract.json; run {Path(__file__).name}')
        elif not path.exists() or path.read_text() != contents:
            path.write_text(contents)
    print('PASS: C/Go ABI constants match contract.json')


if __name__ == '__main__':
    main()
